#!/usr/bin/env node
/**
 * Concatenates the migrations into one paste-ready file.
 *
 * ── Why ────────────────────────────────────────────────────────────────────
 * The Supabase SQL Editor is a single textarea. Applying four migrations by
 * hand means four pastes, four chances to get the order wrong, and no record of
 * what was actually applied — which is how a project ends up with a half-built
 * schema and a `PGRST205: Could not find the table 'public.transactions' in the
 * schema cache` from PostgREST while the code looks perfectly fine.
 *
 * ── The output is generated, never edited ──────────────────────────────────
 * `supabase/migrations/*.sql` stays the source of truth. The bundle is
 * gitignored, so the two cannot drift — the same reason `@wallet/shared` is
 * consumed as source rather than as a build artifact.
 *
 * It deliberately writes **outside** `supabase/migrations/`: both
 * `scripts/check-sql.py` and `scripts/check-sql-live.mjs` glob that directory,
 * and a second copy of the schema sitting inside it would be applied twice.
 *
 * ── Usage ──────────────────────────────────────────────────────────────────
 *   node scripts/bundle-migrations.mjs                 # -> supabase/apply-all.sql
 *   node scripts/bundle-migrations.mjs --from 0005     # -> apply-from-0005.sql
 *   node scripts/bundle-migrations.mjs --stdout        # print instead of writing
 *
 * `--from` exists for the partially-migrated project: when `check:supabase`
 * reports only the newest objects missing, re-pasting the earlier migrations
 * re-runs their `create or replace function` bodies over a live database, which
 * silently discards anything edited in the dashboard since. Paste the tail
 * instead.
 *
 * Then: Supabase Dashboard -> SQL Editor -> New query -> paste the whole file
 * -> Run. Finish by running `pnpm check:supabase` to confirm it took.
 */

import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO_ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const MIGRATIONS_DIR = join(REPO_ROOT, 'supabase', 'migrations');

const toStdout = process.argv.includes('--stdout');

const fromArg = process.argv.indexOf('--from');
const from = fromArg === -1 ? null : process.argv[fromArg + 1];
if (fromArg !== -1 && !from) {
  console.error('--from needs a migration prefix, e.g. --from 0005');
  process.exit(2);
}

const OUTPUT = join(
  REPO_ROOT,
  'supabase',
  from ? `apply-from-${from}.sql` : 'apply-all.sql',
);

function rule(title) {
  const line = '-- ' + '='.repeat(74);
  return `${line}\n--  ${title}\n${line}\n`;
}

let files = readdirSync(MIGRATIONS_DIR)
  .filter((name) => name.endsWith('.sql'))
  .sort();

if (files.length === 0) {
  console.error(`No .sql files in ${relative(REPO_ROOT, MIGRATIONS_DIR)}`);
  process.exit(2);
}

if (from) {
  // A prefix, not an exact name — `--from 5` and `--from 0005` both work, and a
  // renamed-but-renumbered file does not silently drop out of the bundle.
  const start = files.findIndex((name) => name.startsWith(from));
  if (start === -1) {
    console.error(`No migration starts with "${from}". Available: ${files.join(', ')}`);
    process.exit(2);
  }
  files = files.slice(start);
}

const scope = from
  ? `--  Migrations ${files[0].replace(/\.sql$/, '')} onward ONLY (${files.length} of them).\n` +
    `--  The earlier migrations are assumed to be applied already — this file is\n` +
    `--  NOT a complete schema. For a fresh project, run without --from.\n`
  : `--  Every statement is idempotent, so re-running the whole file is safe.\n`;

const header = `${rule('Sara Wallet — migrations')}
--  GENERATED by scripts/bundle-migrations.mjs — do not edit.
--
--  Source of truth: supabase/migrations/*.sql
--  Regenerate with: pnpm migrations:bundle${from ? ` --from ${from}` : ''}
--
${scope}--  Paste into Supabase Dashboard -> SQL Editor -> New query -> Run.
`;

const parts = [header];

for (const name of files) {
  const sql = readFileSync(join(MIGRATIONS_DIR, name), 'utf8').trimEnd();
  parts.push(`\n\n${rule(name)}\n\n${sql}\n`);
}

// One trailing NOTIFY so PostgREST picks the schema up immediately rather than
// on its next poll. Each migration already does this; this is belt and braces
// for the single-paste case.
parts.push(`\n\n${rule('Reload the PostgREST schema cache')}\n\nnotify pgrst, 'reload schema';\n`);

const bundle = parts.join('');

if (toStdout) {
  process.stdout.write(bundle);
} else {
  writeFileSync(OUTPUT, bundle, 'utf8');
  const kb = (Buffer.byteLength(bundle, 'utf8') / 1024).toFixed(1);
  console.log(`${relative(REPO_ROOT, OUTPUT).replace(/\\/g, '/')}  (${kb} kB)`);
  console.log(`${files.length} migrations: ${files.join(', ')}`);
  console.log('\nPaste it into Supabase -> SQL Editor -> New query -> Run.');
  console.log('Then verify with: pnpm check:supabase');
}
